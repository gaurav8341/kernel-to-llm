// P01 tool — sweep block shapes and matrix sizes for the naive SGEMM.
//
// Usage:
//   ./bin/sgemm_probe
//   ./bin/sgemm_probe --sizes 1024,4096 --blocks 32x8,16x16,8x32 --reps 5
//   ./bin/sgemm_probe --sizes 15360 --blocks 32x8 --no-verify
//
// ---------------------------------------------------------------------------
// WHY THIS EXISTS, and how it differs from correctness/ and bench/.
//
// correctness/ is capped by its CPU oracle: O(M*N*K) scalar work, measured at
// 116 s for 3072^3 against a 0.21 s kernel, and it keeps four host buffers so it
// runs out of host RAM near N ~ 11000. bench/ answers a fixed question about a
// fixed set of variants.
//
// This tool exists to answer "what happens if I change the launch geometry",
// which neither of those can do, and to reach sizes neither can reach. It gets
// past both limits by keeping everything on the GPU:
//
//   - inputs are generated BY A KERNEL, so no host buffers and no H2D copies
//   - the reference is cuBLAS, not a triple loop
//   - the error reduction runs on the device, so only 256 floats come back
//
// The practical ceiling is then just VRAM: 4 buffers of N^2 fp32, which on a
// 4 GB card tops out at N = 15529 (measured; 15530 fails to allocate).
//
// ---------------------------------------------------------------------------
// WHAT IT MEASURES, and the hypothesis it is built to test.
//
// It drives the variants through their LAUNCHERS, using the optional block
// override in the SgemmLauncher contract (see src/sgemm.cuh). So what it times
// is the real call path that correctness/ and bench/ use — there is no second
// copy of the launch logic here that could drift from src/.
//
// The hypothesis: in the naive kernel threadIdx.x maps to the COLUMN, so a
// warp's 32 lanes are consecutive columns of one row. Consecutive columns are
// consecutive addresses in row-major C and B, so a block whose x extent is a
// full 32 lets each warp issue one coalesced transaction, while a block 8 wide
// splits every warp across four rows of C.
//
// MEASURED (N=4096, best of 3), which is why the tool is worth having:
//
//     32x32  (1024 thr)  388.9 ms   0.353 TFLOPS   12.1% of cuBLAS
//     64x16  (1024 thr)  390.5 ms   0.352 TFLOPS   12.0%
//     16x16  ( 256 thr)  425.4 ms   0.323 TFLOPS   11.0%
//     32x8   ( 256 thr)  444.1 ms   0.309 TFLOPS   10.6%
//     8x32   ( 256 thr)  509.8 ms   0.270 TFLOPS    9.2%
//     8x8    (  64 thr)  547.8 ms   0.251 TFLOPS    8.6%
//
// The direction holds — 32x8 beats 8x32 at equal thread count — but only by
// 1.15x, not the several-fold gap a pure "1 transaction vs 4" story predicts.
// And 16x16 matches 32x8 despite its sub-warp x extent. Two reasons: B's load
// does not depend on the row, so the lanes sharing a column broadcast from
// cache rather than issuing separate transactions; and the whole kernel is so
// starved for arithmetic intensity that it is bound by total bytes moved, which
// no block shape changes. Threads per block (occupancy) ends up mattering as
// much as shape: the two 1024-thread configs win regardless of aspect ratio.
//
// Total spread is only 1.4x. Tiling is what moves this number, not geometry —
// which is itself the useful finding, and the reason Week 3 exists.
//
// Only variants with block_is_free get swept. The tiled kernel's block size is
// not free — its shared tiles are declared [TILE_DIM][TILE_DIM], so block and
// tile must agree — so it gets a single row at its own geometry. Sweep that one
// with a rebuilt `make TILE=32`.
// ---------------------------------------------------------------------------
#include "sgemm.cuh"

#include <cublas_v2.h>

#include <cfloat>
#include <cstring>
#include <string>
#include <vector>

#define CUBLAS_CHECK(call)                                                       \
do {                                                                             \
    cublasStatus_t cublas_status = (call);                                       \
    if (cublas_status != CUBLAS_STATUS_SUCCESS) {                                \
        fprintf(stderr, "CUBLAS ERROR %d at %s:%d\n",                            \
                (int)cublas_status, __FILE__, __LINE__);                         \
        exit(EXIT_FAILURE);                                                      \
    }                                                                            \
} while (0)

// ---------------------------------------------------------------------------
// Inputs, generated on the device.
//
// A hash of the index rather than a PRNG: it needs no state, so every element
// is computed independently and the result is identical on every run and every
// size. (It does NOT match initialize_matrix() in sgemm.cuh — this tool checks
// against cuBLAS on the same inputs, so the two only have to agree with each
// other, not with correctness/.)
// ---------------------------------------------------------------------------
__global__ void fillKernel(float *buf, size_t n, unsigned seed) {
    const size_t i = blockIdx.x * (size_t)blockDim.x + threadIdx.x;
    if (i >= n) return;
    unsigned x = (unsigned)i * 2654435761u + seed;
    x ^= x >> 15; x *= 2246822519u; x ^= x >> 13;
    buf[i] = (float)((double)x / 4294967296.0 * 2.0 - 1.0);   // [-1, 1)
}

// ---------------------------------------------------------------------------
// Error reduction, on the device.
//
// Same verdict rule as check.cuh: an element is bad only when it exceeds BOTH
// the relative tolerance AND the absolute floor. A bare max_rel threshold
// false-alarms on outputs that land near zero — which is the exact case the
// floor exists for — and would report a correct kernel as broken.
// ---------------------------------------------------------------------------
#define RBLOCKS  256
#define RTHREADS 256
__global__ void maxErrKernel(const float *ref, const float *got, size_t n,
                             float *outAbs, float *outRel,
                             unsigned long long *outBad,
                             float absFloor, float relTol) {
    __shared__ float sa[RTHREADS], sr[RTHREADS];
    __shared__ unsigned long long sb[RTHREADS];

    float maxAbs = 0.0f, maxRel = 0.0f;
    unsigned long long bad = 0;

    // Grid-stride loop: a fixed 256x256 grid walks an arbitrarily large buffer,
    // so the reduction's launch geometry does not depend on N.
    for (size_t i = blockIdx.x * (size_t)blockDim.x + threadIdx.x; i < n;
         i += (size_t)blockDim.x * gridDim.x) {
        const float a = ref[i], b = got[i];
        if (!isfinite(a) || !isfinite(b)) {          // before any tolerance maths
            maxAbs = INFINITY; maxRel = INFINITY; ++bad; continue;
        }
        const float absErr = fabsf(a - b);
        const float relErr = absErr / fmaxf(fabsf(a), absFloor);
        maxAbs = fmaxf(maxAbs, absErr);
        maxRel = fmaxf(maxRel, relErr);
        if (relErr > relTol && absErr > absFloor) ++bad;
    }

    sa[threadIdx.x] = maxAbs; sr[threadIdx.x] = maxRel; sb[threadIdx.x] = bad;
    __syncthreads();
    for (int s = blockDim.x / 2; s > 0; s >>= 1) {
        if (threadIdx.x < s) {
            sa[threadIdx.x]  = fmaxf(sa[threadIdx.x], sa[threadIdx.x + s]);
            sr[threadIdx.x]  = fmaxf(sr[threadIdx.x], sr[threadIdx.x + s]);
            sb[threadIdx.x] += sb[threadIdx.x + s];
        }
        __syncthreads();
    }
    if (threadIdx.x == 0) {
        outAbs[blockIdx.x] = sa[0];
        outRel[blockIdx.x] = sr[0];
        outBad[blockIdx.x] = sb[0];
    }
}

// ---------------------------------------------------------------------------
// Argument parsing
// ---------------------------------------------------------------------------
// Occupancy and register counts are properties of the KERNEL, so the occupancy
// API needs the kernel symbol rather than the launcher. A __global__ function's
// host-side stub has external linkage, so declaring it and linking the objects
// is enough. This is the one place the tool has to know kernel names; the
// timing path still goes through the launchers.
__global__ void sgemmNaiveKernel(int M, int N, int K, float alpha,
                                 const float *A, const float *B,
                                 float beta, float *C);
__global__ void sgemmTiledKernel(int M, int N, int K, float alpha,
                                 const float *A, const float *B,
                                 float beta, float *C);

static const void *kernel_symbol(const char *variant) {
    if (!strcmp(variant, "naive")) return (const void *)sgemmNaiveKernel;
    if (!strcmp(variant, "tiled")) return (const void *)sgemmTiledKernel;
    return nullptr;
}

struct Block { int x, y; };

static bool parse_sizes(const char *arg, std::vector<int> &out) {
    out.clear();
    const char *p = arg;
    while (*p) {
        char *end = nullptr;
        const long v = strtol(p, &end, 10);
        if (end == p || v <= 0 || v > 100000) return false;
        out.push_back((int)v);
        p = (*end == ',') ? end + 1 : end;
        if (*end && *end != ',') return false;
    }
    return !out.empty();
}

static bool parse_blocks(const char *arg, std::vector<Block> &out) {
    out.clear();
    const char *p = arg;
    while (*p) {
        int bx = 0, by = 0, consumed = 0;
        if (sscanf(p, "%dx%d%n", &bx, &by, &consumed) != 2) return false;
        if (bx <= 0 || by <= 0) return false;
        out.push_back({bx, by});
        p += consumed;
        if (*p == ',') ++p;
        else if (*p) return false;
    }
    return !out.empty();
}

static void usage(const char *argv0) {
    fprintf(stderr,
      "usage: %s [options]\n"
      "  --sizes  N[,N...]      square sizes to sweep     (default 512,1024,2048,4096)\n"
      "  --blocks BXxBY[,...]   block shapes to sweep     (default 32x8,16x16,8x32,32x32)\n"
      "  --reps   N             timed runs, best is kept  (default 3)\n"
      "  --only   naive|tiled   sweep one variant instead of all\n"
      "  --no-verify            skip the cuBLAS comparison (saves one GEMM)\n"
      "\n"
      "BX is the COLUMN extent. Each shape must satisfy BX*BY <= 1024 on sm_86.\n", argv0);
}

// ---------------------------------------------------------------------------
int main(int argc, char **argv) {
    std::vector<int>   sizes  = {512, 1024, 2048, 4096};
    std::vector<Block> blocks = {{32, 8}, {16, 16}, {8, 32}, {32, 32}};
    int  reps   = 3;
    bool verify = true;
    const char *only = nullptr;      // nullptr = every variant

    for (int i = 1; i < argc; ++i) {
        if (!strcmp(argv[i], "--sizes") && i + 1 < argc) {
            if (!parse_sizes(argv[++i], sizes)) {
                fprintf(stderr, "probe: bad --sizes list\n"); return 2; }
        } else if (!strcmp(argv[i], "--blocks") && i + 1 < argc) {
            if (!parse_blocks(argv[++i], blocks)) {
                fprintf(stderr, "probe: bad --blocks list (want e.g. 32x8,16x16)\n"); return 2; }
        } else if (!strcmp(argv[i], "--reps") && i + 1 < argc) {
            reps = atoi(argv[++i]);
            if (reps < 1) { fprintf(stderr, "probe: --reps must be >= 1\n"); return 2; }
        } else if (!strcmp(argv[i], "--only") && i + 1 < argc) {
            only = argv[++i];
        } else if (!strcmp(argv[i], "--no-verify")) {
            verify = false;
        } else {
            usage(argv[0]); return 2;
        }
    }

    int nvariants = 0;
    const SgemmVariant *variants = sgemm_variants(&nvariants);

    // A typo in --only must not silently sweep nothing and exit 0.
    if (only && strcmp(only, "all") != 0) {
        bool known = false;
        for (int i = 0; i < nvariants; ++i)
            if (!strcmp(only, variants[i].name)) known = true;
        if (!known) {
            fprintf(stderr, "probe: unknown --only \"%s\"; known variants are", only);
            for (int i = 0; i < nvariants; ++i) fprintf(stderr, " %s", variants[i].name);
            fprintf(stderr, " all\n");
            return 2;
        }
    }

    // Reject illegal geometry up front, with the reason. A launch with
    // blockDim.x*blockDim.y over the limit fails at runtime with a bare
    // cudaErrorInvalidConfiguration, which does not say which limit was hit.
    int maxThreads = 0;
    for (const Block &b : blocks) {
        if (!sgemm_block_fits_device(dim3(b.x, b.y), &maxThreads)) {
            fprintf(stderr, "probe: block %dx%d = %d threads exceeds the device limit of %d\n",
                    b.x, b.y, b.x * b.y, maxThreads);
            return 2;
        }
    }

    cublasHandle_t handle;
    CUBLAS_CHECK(cublasCreate(&handle));
    const float alpha = 1.0f, beta = 0.0f;

    float *dMaxAbs, *dMaxRel; unsigned long long *dBad;
    CUDA_CHECK(cudaMalloc(&dMaxAbs, RBLOCKS * sizeof(float)));
    CUDA_CHECK(cudaMalloc(&dMaxRel, RBLOCKS * sizeof(float)));
    CUDA_CHECK(cudaMalloc(&dBad,    RBLOCKS * sizeof(unsigned long long)));
    std::vector<float> hMaxAbs(RBLOCKS), hMaxRel(RBLOCKS);
    std::vector<unsigned long long> hBad(RBLOCKS);

    // ----- static facts, printed once ---------------------------------------
    // No profiler and no run-to-run noise: this is arithmetic over the device
    // limits plus the compiler's register allocation.
    cudaDeviceProp prop;
    int dev = 0, clockKhz = 0;
    CUDA_CHECK(cudaGetDevice(&dev));
    CUDA_CHECK(cudaGetDeviceProperties(&prop, dev));
    // cudaDeviceProp::clockRate was REMOVED in CUDA 13 (this box is on 13.1).
    CUDA_CHECK(cudaDeviceGetAttribute(&clockKhz, cudaDevAttrClockRate, dev));
    const int warpsPerSmMax = prop.maxThreadsPerMultiProcessor / prop.warpSize;

    printf("device  %s  sm_%d%d   %d SMs   %d thr/SM (%d warps)   "
           "%d blk/SM   %d reg/SM   %.3f GHz\n",
           prop.name, prop.major, prop.minor, prop.multiProcessorCount,
           prop.maxThreadsPerMultiProcessor, warpsPerSmMax,
           prop.maxBlocksPerMultiProcessor, prop.regsPerMultiprocessor,
           (double)clockKhz * 1e-6);

    for (int i = 0; i < nvariants; ++i) {
        if (!sgemm_variant_selected(variants[i].name, only)) continue;
        const void *sym = kernel_symbol(variants[i].name);
        if (!sym) continue;
        cudaFuncAttributes fa;
        CUDA_CHECK(cudaFuncGetAttributes(&fa, sym));
        printf("kernel  %-6s %d reg/thread   %zu B shared   %zu B local%s\n",
               variants[i].name, fa.numRegs, (size_t)fa.sharedSizeBytes,
               (size_t)fa.localSizeBytes,
               fa.localSizeBytes ? "   <- SPILLING" : " (no spills)");
    }
    printf("\n");

    for (int si = 0; si < (int)sizes.size(); ++si) {
        const int    N     = sizes[si];
        const size_t n2    = (size_t)N * (size_t)N;
        const size_t bytes = n2 * sizeof(float);
        const double fl    = gemm_flops(N, N, N);

        size_t freeB = 0, totalB = 0;
        CUDA_CHECK(cudaMemGetInfo(&freeB, &totalB));

        // Four buffers: A, B, C, and the cuBLAS reference. Checked by hand
        // rather than with CUDA_CHECK — running out of memory is an EXPECTED
        // outcome of a size sweep, not a reason to abort the whole run.
        float *dA = nullptr, *dB = nullptr, *dC = nullptr, *dRef = nullptr;
        cudaError_t e = cudaSuccess;
        if (e == cudaSuccess) e = cudaMalloc(&dA,   bytes);
        if (e == cudaSuccess) e = cudaMalloc(&dB,   bytes);
        if (e == cudaSuccess) e = cudaMalloc(&dC,   bytes);
        if (e == cudaSuccess) e = cudaMalloc(&dRef, bytes);
        if (e != cudaSuccess) {
            printf("N=%d: needs %.3f GB, only %.3f GB free -> %s\n\n",
                   N, 4.0 * (double)bytes / 1e9, (double)freeB / 1e9,
                   cudaGetErrorName(e));
            cudaFree(dA); cudaFree(dB); cudaFree(dC); cudaFree(dRef);
            cudaGetLastError();                 // clear the sticky OOM
            continue;
        }

        const int fillBlocks = (int)((n2 + 255) / 256);
        fillKernel<<<fillBlocks, 256>>>(dA, n2, 1234u);
        fillKernel<<<fillBlocks, 256>>>(dB, n2, 5678u);
        CUDA_CHECK(cudaGetLastError());
        CUDA_CHECK(cudaDeviceSynchronize());

        // cuBLAS baseline. Row-major C = A*B through a column-major library:
        // a row-major MxN matrix is bit-for-bit a column-major NxM one, i.e.
        // its transpose, and (A*B)^T = B^T * A^T. So handing cuBLAS B then A
        // with M and N swapped computes C^T into the same bytes that read back
        // as row-major C. No transpose kernel, no copy.
        double cublasMs = 0.0;
        {
            CUBLAS_CHECK(cublasSgemm(handle, CUBLAS_OP_N, CUBLAS_OP_N, N, N, N,
                                     &alpha, dB, N, dA, N, &beta, dRef, N));
            CUDA_CHECK(cudaDeviceSynchronize());          // warmup, untimed
            cublasMs = 1e30;
            for (int r = 0; r < reps; ++r) {
                GpuTimer t("cublas");
                t.start();
                CUBLAS_CHECK(cublasSgemm(handle, CUBLAS_OP_N, CUBLAS_OP_N, N, N, N,
                                         &alpha, dB, N, dA, N, &beta, dRef, N));
                t.stop();
                const double ms = t.elapsed();
                if (ms < cublasMs) cublasMs = ms;
            }
        }

        printf("N=%d   %.3f GB allocated   cuBLAS %8.2f ms  %6.3f TFLOPS   (best of %d)\n",
               N, 4.0 * (double)bytes / 1e9, cublasMs, fl / (cublasMs / 1e3) / 1e12, reps);

        // Memory accounting for the NAIVE access pattern: 2 loads per k per
        // output element. It bounds the kernel from two directions at once.
        //
        //   DRAM floor  if every byte were loaded once and cached perfectly:
        //               A + B read once, C written once.
        //   LSU floor   an SM retires at most one warp-wide load per clock
        //               (32 lanes), so this many lane-loads cannot issue any
        //               faster however well the cache hides DRAM.
        //
        // A measured time near the LSU floor and orders of magnitude above the
        // DRAM floor means the kernel is bound by the NUMBER of load
        // instructions, not by bandwidth — a different fix.
        {
            const double nn      = (double)N;
            const double laneLd  = 2.0 * nn * nn * nn;
            const double noCache = laneLd * 4.0;
            const double ideal   = 3.0 * nn * nn * 4.0;
            const double bwPeak  = 176.03e9;        // docs/hardware-spec-sheet.md
            const double peakTf  = 2.0 * prop.multiProcessorCount * 128.0
                                 * ((double)clockKhz * 1e3) / 1e12;
            printf("  memory: %.3e lane-loads   AI %.3f FLOP/B (ridge %.1f)   "
                   "uncached %.0f ms   DRAM floor %.2f ms   LSU floor %.1f ms\n",
                   laneLd, fl / noCache, peakTf * 1e12 / bwPeak,
                   1e3 * noCache / bwPeak, 1e3 * ideal / bwPeak,
                   1e3 * laneLd / (32.0 * prop.multiProcessorCount
                                   * (double)clockKhz * 1e3));
        }

        printf("  %-15s %6s %9s %7s %8s %6s %10s %10s %8s %8s %10s %8s\n",
               "variant block", "thr", "grid", "blk/SM", "warp/SM", "occ%",
               "limit", "best ms", "TFLOPS", "%cuBLAS", "max_rel", "verdict");

        for (int vi = 0; vi < nvariants; ++vi) {
            const SgemmVariant &variant = variants[vi];
            if (!sgemm_variant_selected(variant.name, only)) continue;

            // A fixed-geometry variant gets exactly ONE row: sweeping it would
            // relaunch the identical configuration and invite the reader to
            // compare numbers that differ only by noise.
            const int nruns = variant.block_is_free ? (int)blocks.size() : 1;

        for (int bi = 0; bi < nruns; ++bi) {
            const Block b = variant.block_is_free ? blocks[bi] : Block{TILE_DIM, TILE_DIM};

            // The sentinel from sgemm.cuh: a zero extent asks the launcher for
            // its own default. Passed only for fixed-geometry variants, whose
            // contract (block_is_free == false) is TILE_DIM x TILE_DIM.
            const dim3 blockSize = variant.block_is_free ? dim3(b.x, b.y) : dim3(0, 0);
            const dim3 gridSize((N + b.x - 1) / b.x, (N + b.y - 1) / b.y);

            // gridDim.y and .z are capped at 65535 on every CUDA device to date,
            // while gridDim.x gets a full 2^31-1. A tall thin block (by = 1) at
            // large N is the way to trip it.
            if (gridSize.y > 65535u) {
                printf("  %-5s %-9s %7d  grid.y=%u exceeds the 65535 limit\n",
                       variant.name, (std::to_string(b.x) + "x" + std::to_string(b.y)).c_str(),
                       b.x * b.y, gridSize.y);
                continue;
            }

            double bestMs = 1e30;
            bool   failed = false;
            for (int r = 0; r < reps + 1; ++r) {          // r == 0 is the warmup
                CUDA_CHECK(cudaMemset(dC, 0, bytes));
                GpuTimer t(variant.name);
                t.start();
                variant.fn(N, N, N, alpha, dA, dB, beta, dC, blockSize);
                t.stop();
                const cudaError_t le = cudaGetLastError();
                if (le != cudaSuccess) {
                    printf("  %-5s %-9s %7d  LAUNCH FAILED: %s\n",
                           variant.name, (std::to_string(b.x) + "x" + std::to_string(b.y)).c_str(),
                           b.x * b.y, cudaGetErrorName(le));
                    failed = true; break;
                }
                const double ms = t.elapsed();            // syncs on stopEvent
                if (r > 0 && ms < bestMs) bestMs = ms;
            }
            if (failed) continue;

            double maxRel = 0.0; unsigned long long bad = 0;
            if (verify) {
                const float absFloor = 4.0f * FLT_EPSILON * (float)N;
                const float relTol   = 1e-3f;   // vs cuBLAS: looser than vs the CPU oracle,
                                                // because cuBLAS reorders the K sum
                maxErrKernel<<<RBLOCKS, RTHREADS>>>(dRef, dC, n2, dMaxAbs, dMaxRel, dBad,
                                                    absFloor, relTol);
                CUDA_CHECK(cudaGetLastError());
                CUDA_CHECK(cudaMemcpy(hMaxRel.data(), dMaxRel, RBLOCKS * sizeof(float),
                                      cudaMemcpyDeviceToHost));
                CUDA_CHECK(cudaMemcpy(hBad.data(), dBad, RBLOCKS * sizeof(unsigned long long),
                                      cudaMemcpyDeviceToHost));
                for (int i = 0; i < RBLOCKS; ++i) {
                    if (hMaxRel[i] > maxRel) maxRel = hMaxRel[i];
                    bad += hBad[i];
                }
            }

            const double tf = fl / (bestMs / 1e3) / 1e12;

            // Rate columns ONLY when the result was verified correct. A kernel
            // that computes nothing times at 0.001 ms and "achieves" 2097
            // TFLOPS at 78900% of cuBLAS on a 4.33 TFLOPS card. The elapsed ms
            // still prints on a failure — it tells you whether it ran at all —
            // but a throughput derived from a wrong answer measures nothing.
            const bool trust = !verify || bad == 0;
            char tfStr[24], pctStr[24];
            if (trust) {
                snprintf(tfStr,  sizeof(tfStr),  "%.3f", tf);
                snprintf(pctStr, sizeof(pctStr), "%.1f%%",
                         100.0 * tf / (fl / (cublasMs / 1e3) / 1e12));
            } else {
                snprintf(tfStr,  sizeof(tfStr),  "-");
                snprintf(pctStr, sizeof(pctStr), "-");
            }

            // THEORETICAL occupancy: static, from registers / shared memory /
            // block size. ACHIEVED occupancy — what fraction of warp slots were
            // really filled and issuing across the whole run — is always <=
            // this and needs ncu --section Occupancy. With this many waves of
            // blocks over the machine, tail effects are negligible and the two
            // land close together.
            int    blocksPerSm = 0, warpsPerSm = 0;
            double occ = 0.0;
            char   limiter[32] = "-";
            if (const void *sym = kernel_symbol(variant.name)) {
                cudaFuncAttributes fa;
                CUDA_CHECK(cudaFuncGetAttributes(&fa, sym));
                CUDA_CHECK(cudaOccupancyMaxActiveBlocksPerMultiprocessor(
                               &blocksPerSm, sym, b.x * b.y, 0));
                const int warpsPerBlock =
                    (b.x * b.y + prop.warpSize - 1) / prop.warpSize;
                warpsPerSm = blocksPerSm * warpsPerBlock;
                occ = 100.0 * (double)warpsPerSm / (double)warpsPerSmMax;

                // Report EVERY ceiling that ties for tightest, not just one.
                // At 1024 threads and 40 registers both the register budget and
                // the warp-slot budget allow exactly 1 block, and naming only
                // the first would suggest that relieving it alone would help.
                // ncu prints these as Block Limit Registers / Warps / Shared Mem.
                const int byRegs = fa.numRegs
                    ? prop.regsPerMultiprocessor / (fa.numRegs * prop.warpSize * warpsPerBlock)
                    : prop.maxBlocksPerMultiProcessor;
                const int byWarps  = warpsPerSmMax / warpsPerBlock;
                const int byBlocks = prop.maxBlocksPerMultiProcessor;
                const int tightest = (byRegs < byWarps ? byRegs : byWarps) < byBlocks
                                   ? (byRegs < byWarps ? byRegs : byWarps) : byBlocks;
                if (warpsPerSm >= warpsPerSmMax) {
                    // Every warp slot is filled, so naming a "limit" here would
                    // imply occupancy headroom is being lost when none is.
                    snprintf(limiter, sizeof(limiter), "none");
                } else {
                    limiter[0] = '\0';
                    if (byRegs   == tightest) strcat(limiter, "reg");
                    if (byWarps  == tightest) strcat(limiter, limiter[0] ? "+warp" : "warp");
                    if (byBlocks == tightest) strcat(limiter, limiter[0] ? "+blk" : "blk");
                }
            }

            char gridStr[32];
            snprintf(gridStr, sizeof(gridStr), "%ux%u", gridSize.x, gridSize.y);
            char blockStr[48];
            snprintf(blockStr, sizeof(blockStr), "%-5s %dx%d", variant.name, b.x, b.y);

            printf("  %-15s %6d %9s %7d %8d %5.1f%% %10s %10.3f %8s %8s %10.2e %8s%s\n",
                   blockStr, b.x * b.y, gridStr, blocksPerSm, warpsPerSm, occ,
                   limiter, bestMs, tfStr, pctStr,
                   maxRel, verify ? (bad ? "FAIL" : "PASS") : "skipped",
                   // Factual note, not a verdict: with blockDim.x < 32 a warp's
                   // 32 lanes straddle more than one row of C. Measured cost is
                   // real but modest — see the table in the header.
                   (b.x < 32) ? "   <- warp spans >1 row of C" : "");
        }
        }
        printf("\n");

        CUDA_CHECK(cudaFree(dA));   CUDA_CHECK(cudaFree(dB));
        CUDA_CHECK(cudaFree(dC));   CUDA_CHECK(cudaFree(dRef));
    }

    CUDA_CHECK(cudaFree(dMaxAbs)); CUDA_CHECK(cudaFree(dMaxRel)); CUDA_CHECK(cudaFree(dBad));
    CUBLAS_CHECK(cublasDestroy(handle));
    return 0;
}
